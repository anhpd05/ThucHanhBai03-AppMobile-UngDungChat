import type { Message } from '../types/models';
import { minutesAgo } from '../utils/formatTime';

function message(
  conversationId: string,
  index: number,
  senderId: string,
  text: string,
  minutes: number,
): Message {
  return {
    id: `${conversationId}-${index}`,
    conversationId,
    senderId,
    text,
    createdAt: minutesAgo(minutes),
  };
}

